// Generates a DEMO ECDSA P-256 key pair and writes it to src/data/demo-keys.ts.
// DEMO DATA ONLY. The private key is committed on purpose. Never use it in production.
// Usage: npm run keys
import { writeFileSync } from 'node:fs';
import { webcrypto } from 'node:crypto';

const { subtle } = webcrypto;

const pair = await subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify']);
const publicJwk = await subtle.exportKey('jwk', pair.publicKey);
const privateJwk = await subtle.exportKey('jwk', pair.privateKey);

// Keep only the fields we need, in a stable order.
const pick = (jwk, fields) => Object.fromEntries(fields.map((f) => [f, jwk[f]]));
const publicFields = ['kty', 'crv', 'x', 'y'];
const privateFields = ['kty', 'crv', 'x', 'y', 'd'];

const source = `// DEMO KEY, NOT FOR PRODUCTION.
// This key pair is demo data. The private key is public on purpose, so anyone can forge a pass.
// Generated by scripts/generate-demo-keys.mjs. Do not reuse these keys anywhere real.

export interface DemoKeyPair {
  readonly publicKey: JsonWebKey;
  readonly privateKey: JsonWebKey;
}

export const DEMO_KEYS: DemoKeyPair = {
  publicKey: ${JSON.stringify(pick(publicJwk, publicFields), null, 2).replace(/\n/g, '\n  ')},
  privateKey: ${JSON.stringify(pick(privateJwk, privateFields), null, 2).replace(/\n/g, '\n  ')},
};
`;

writeFileSync(new URL('../src/data/demo-keys.ts', import.meta.url), source);
console.log('Wrote src/data/demo-keys.ts (DEMO KEY, NOT FOR PRODUCTION)');
